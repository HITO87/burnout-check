export function getCombinationText(primary: StrengthType, secondary: StrengthType): string {
  const p = STRENGTH_TYPES[primary]
  const s = STRENGTH_TYPES[secondary]
  const key = `${primary}_${secondary}`
  return COMBINATION_TEXTS[key] || generateDefaultCombination(p.name, p.oneLiner, s.name, s.oneLiner)
}

